"""Regressions for the code review of the hardening branch."""

import subprocess
from pathlib import Path

import pytest

from sdd_pilot import config, graph
from sdd_pilot import state as run_state
from sdd_pilot.worktree import fingerprint


def _git(root: Path, *args: str) -> None:
    subprocess.run(["git", *args], cwd=root, check=True, capture_output=True)


@pytest.fixture
def git_repo(repo: Path) -> Path:
    """The demo repo as a git repository with no .gitignore at all."""
    _git(repo, "init", "-q")
    _git(repo, "config", "user.email", "t@example.com")
    _git(repo, "config", "user.name", "t")
    _git(repo, "add", ".")
    _git(repo, "commit", "-q", "-m", "init")
    return repo


def test_run_state_never_changes_the_fingerprint_even_unignored(git_repo: Path) -> None:
    cfg = config.load(git_repo)
    cfg = config.Config(**{**vars(cfg), "graphify_auto": False})  # no .gitignore written
    run_state.start(cfg, "009", check_branch=False)
    first, _ = run_state.next_step(cfg)["tasks"]
    run_state.record_pass(cfg)  # save() rewrites .sdd/state.json and dashboard.html
    run_state.record_review(cfg, first, "clean")
    run_state.complete(cfg, first)


@pytest.mark.parametrize(
    "generated", [".coverage", "htmlcov/index.html", ".graphifyignore", "graphify-out/g.json"]
)
def test_generated_files_do_not_count(git_repo: Path, generated: str) -> None:
    before = fingerprint(git_repo)
    target = git_repo / generated
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text("regenerated by a tool")
    assert fingerprint(git_repo) == before


def test_repo_without_commits_uses_git_listing(repo: Path) -> None:
    _git(repo, "init", "-q")
    (repo / ".gitignore").write_text("out-of-tree/\n")
    before = fingerprint(repo)
    (repo / "out-of-tree").mkdir()
    (repo / "out-of-tree" / "big.bin").write_text("ignored build output")
    assert fingerprint(repo) == before
    (repo / "new.py").write_text("x = 1\n")
    assert fingerprint(repo) != before


def test_rest_of_a_group_keeps_its_gate_and_review(cfg: config.Config) -> None:
    run_state.start(cfg, "009", check_branch=False)
    first, second = run_state.next_step(cfg)["tasks"]
    run_state.record_pass(cfg)
    run_state.record_review(cfg, first, "clean")
    run_state.complete(cfg, first)
    assert run_state.next_step(cfg)["tasks"] == [second]  # `next` between the two ticks
    run_state.complete(cfg, second)


def test_new_group_starts_with_a_fresh_gate(cfg: config.Config) -> None:
    run_state.start(cfg, "009", check_branch=False)
    first, second = run_state.next_step(cfg)["tasks"]
    run_state.record_pass(cfg)
    run_state.record_review(cfg, first, "clean")
    run_state.complete(cfg, first)
    run_state.complete(cfg, second)
    step = run_state.next_step(cfg)
    assert step["tasks"] == ["T-009-04"]
    with pytest.raises(ValueError, match="no passing"):
        run_state.complete(cfg, "T-009-04")


def test_review_for_a_task_outside_the_group_is_refused(cfg: config.Config) -> None:
    run_state.start(cfg, "009", check_branch=False)
    run_state.next_step(cfg)
    with pytest.raises(ValueError, match="not in the group in flight"):
        run_state.record_review(cfg, "T-009-05", "clean")


def test_failed_spawn_releases_the_lock(repo: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(graph, "find_graphify", lambda: None)

    def boom(*args: object, **kwargs: object) -> None:
        raise OSError("no such interpreter")

    monkeypatch.setattr(graph.subprocess, "Popen", boom)
    assert graph._real_start(repo, Path("entry.py")) is False  # type: ignore[attr-defined]
    assert not (repo / graph.LOCK_FILE).exists()


def test_start_writes_the_ignore_files_before_the_run(cfg: config.Config) -> None:
    run_state.start(cfg, "009", check_branch=False)
    assert (cfg.root / graph.IGNORE_FILE).exists()
    assert "graphify-out/" in (cfg.root / ".gitignore").read_text()
